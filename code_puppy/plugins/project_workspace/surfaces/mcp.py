# Public API
# ---------------------------------------------------------------------------


def apply_mcp_scope(
    scope: str,
    workspace_root: Path | None,
    *,
    _manager: Any = None,
    _project_file: Path | None = None,
) -> None:
    """Inject / disable MCP servers based on the active workspace scope.

    Args:
        scope:          ``"merge"`` | ``"project"`` | ``"global"``
        workspace_root: From ``discover_root()`` / ``config.root``; may be
                        ``None`` when no workspace was found.
        _manager:       Injectable ``MCPManager`` instance for testing.
                        Defaults to ``get_mcp_manager()`` at call time.
        _project_file:  Injectable path to the project ``mcp_servers.json``
                        file for testing.  Defaults to
                        ``workspace_root / ".code_puppy" / "mcp_servers.json"``.

    Never raises — all errors are logged and execution falls through to
    default global behaviour.
    """
    # global scope: noop — keep whatever the manager loaded from global config
    if scope == "global":
        logger.debug("[project_workspace/mcp] scope=global — noop")
        return

    # Resolve manager
    if _manager is None:
        try:
            from code_puppy.mcp_.manager import get_mcp_manager

            manager = get_mcp_manager()
        except Exception as exc:
            logger.warning(
                "[project_workspace/mcp] could not get MCPManager: %s — skipping",
                exc,
            )
            return
    else:
        manager = _manager

    # No workspace root: fall through to global for all remaining scopes
    if workspace_root is None and _project_file is None:
        logger.debug(
            "[project_workspace/mcp] no workspace root — falling through to global"
        )
        return

    # Resolve project file path
    if _project_file is not None:
        project_file = _project_file
    else:
        project_file = workspace_root / ".code_puppy" / "mcp_servers.json"  # type: ignore[operator]

    # Load project servers
    project_servers = _load_mcp_servers_from_file(project_file)

    # project scope with no project servers → fall through to global
    if scope == "project" and not project_servers:
        logger.debug(
            "[project_workspace/mcp] project scope but no mcp_servers.json "
            "— falling through to global"
        )
        return

    # Snapshot currently registered servers (global, pre-injection)
    try:
        existing_configs = manager.registry.list_all()
    except Exception as exc:
        logger.warning(
            "[project_workspace/mcp] could not list registry servers: %s — skipping",
            exc,
        )
        return

    existing_by_name: dict[str, Any] = {c.name: c for c in existing_configs}

    # Unknown scope: warn + fall back to merge behaviour
    if scope not in ("merge", "project"):
        logger.warning(
            "[project_workspace/mcp] unknown scope %r — falling back to merge",
            scope,
        )

    # Inject project servers (merge + project + unknown fallback)
    _inject_servers(project_servers, manager, existing_by_name)

    # project scope: disable global servers not overridden by project
    if scope == "project":
        project_names = set(project_servers.keys())
        for existing_config in existing_configs:
            if existing_config.name not in project_names:
                try:
                    managed = manager.get_server(existing_config.id)
                    if managed is not None:
                        managed.disable()
                        logger.debug(
                            "[project_workspace/mcp] disabled global server %r",
                            existing_config.name,
                        )
                except Exception as exc:
                    logger.warning(
                        "[project_workspace/mcp] could not disable server %r: %s",
                        existing_config.name,
                        exc,
                    )


