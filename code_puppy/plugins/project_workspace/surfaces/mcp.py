def register() -> None:
    """Wire the MCP surface into a second ``startup`` callback.

    Called at plugin import time from ``register_callbacks.py``.  The
    workspace config is read *inside* the callback body (at call time) so
    that the first ``startup`` callback (which populates ``_active_config``)
    has already fired before this one runs.
    """
    from code_puppy.callbacks import register_callback

    def _mcp_startup() -> None:
        try:
            from code_puppy.plugins.project_workspace.register_callbacks import (
                get_active_config,
            )

            config = get_active_config()
            scope = config.surfaces.get("mcp", "merge")
            workspace_root = config.root

            logger.debug(
                "[project_workspace/mcp] startup fired — scope=%s root=%s",
                scope,
                workspace_root,
            )

            apply_mcp_scope(scope, workspace_root)

        except Exception as exc:
            logger.warning("[project_workspace/mcp] surface error: %s — skipping", exc)

    register_callback("startup", _mcp_startup)
